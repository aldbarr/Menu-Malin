// Menu Malin : cache hors ligne simple.
// Page et images : cache d'abord. deals.json / photos.json : réseau d'abord (actions à jour), cache en secours.
const CACHE = 'menu-malin-v2';
const CORE = ['./', 'index.html', 'manifest.webmanifest', 'deals.json', 'photos.json', 'icon-192.png', 'icon-512.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // polices Google, sites des enseignes : pas de cache
  const fresh = /\.json$/.test(url.pathname) || req.mode === 'navigate';
  if (fresh) {
    e.respondWith(fetch(req).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put(req, c)); return r; }).catch(() => caches.match(req).then(r => r || caches.match('index.html'))));
  } else {
    e.respondWith(caches.match(req).then(r => r || fetch(req).then(n => { const c = n.clone(); caches.open(CACHE).then(x => x.put(req, c)); return n; })));
  }
});
